#!/usr/bin/with-contenv bashio
# ==============================================================================
# Home Assistant Add-on: ntfy
# ==============================================================================

readonly CONFIG_FILE="/etc/ntfy/server.yml"
readonly AUTH_FILE="/data/ntfy/user.db"
readonly HA_TOKEN_FILE="/data/ntfy/ha_token.txt"  # Fix 1: persisted HA token
# Readable copy in the add-on config folder (/addon_configs/<slug>_ntfy/ on the host)
readonly HA_TOKEN_COPY="/config/ha_token.txt"

bashio::log.info "Starting ntfy add-on …"

LOG_LEVEL=$(bashio::config 'log_level' 'INFO')
BASE_URL=$(bashio::config 'base_url' '')
BEHIND_PROXY=$(bashio::config 'behind_proxy' 'false')
AUTH_DEFAULT_ACCESS=$(bashio::config 'auth_default_access' 'deny-all')
ENABLE_SIGNUP=$(bashio::config 'enable_signup' 'true')
ENABLE_LOGIN=$(bashio::config 'enable_login' 'true')
ENABLE_RESERVATIONS=$(bashio::config 'enable_reservations' 'true')
CACHE_DURATION=$(bashio::config 'cache_duration' '12h')
ATTACHMENT_TOTAL=$(bashio::config 'attachment_total_size_limit' '5G')
ATTACHMENT_FILE=$(bashio::config 'attachment_file_size_limit' '15M')
ATTACHMENT_EXPIRY=$(bashio::config 'attachment_expiry_duration' '3h')
VISITOR_ATTACHMENT_TOTAL=$(bashio::config 'visitor_attachment_total_size_limit' '1G')
VISITOR_ATTACHMENT_BANDWIDTH=$(bashio::config 'visitor_attachment_daily_bandwidth_limit' '5G')
KEEPALIVE=$(bashio::config 'keepalive_interval' '45s')
MANAGER=$(bashio::config 'manager_interval' '3m')
VISITOR_REQUEST_LIMIT_BURST=$(bashio::config 'visitor_request_limit_burst' '1000')
VISITOR_REQUEST_LIMIT_REPLENISH=$(bashio::config 'visitor_request_limit_replenish' '1s')
VISITOR_MESSAGE_DAILY_LIMIT=$(bashio::config 'visitor_message_daily_limit' '1000000')
MESSAGE_SIZE_LIMIT=$(bashio::config 'message_size_limit' '4096')
UPSTREAM_URL=$(bashio::config 'upstream_base_url' '')

# ntfy refuses to start with enable-signup but without enable-login ("cannot set
# enable-signup without also setting enable-login"), so sign-up is switched off
# when login is off.
if [ "${ENABLE_LOGIN}" != "true" ] && [ "${ENABLE_SIGNUP}" = "true" ]; then
    bashio::log.info "enable_login is off, disabling enable_signup (sign-up needs login)"
    ENABLE_SIGNUP="false"
fi
ADMIN_USER=$(bashio::config 'admin_username' '')
ADMIN_PASS=$(bashio::config 'admin_password' '')

mkdir -p /data/ntfy/cache /data/ntfy/attachments

bashio::log.info "Generating configuration …"
bashio::log.info "enable-reservations: ${ENABLE_RESERVATIONS}"
bashio::log.info "visitor-request-limit: burst=${VISITOR_REQUEST_LIMIT_BURST} replenish=${VISITOR_REQUEST_LIMIT_REPLENISH}"

cat > "${CONFIG_FILE}" <<EOF
# ntfy server.yml — auto-generated by HA add-on

listen-http: ":4280"

log-level: ${LOG_LEVEL}
log-format: text

behind-proxy: ${BEHIND_PROXY}

cache-file: /data/ntfy/cache/cache.db
cache-duration: "${CACHE_DURATION}"
cache-startup-queries: "pragma journal_mode(WAL); pragma synchronous(NORMAL);"

auth-file: ${AUTH_FILE}
auth-default-access: "${AUTH_DEFAULT_ACCESS}"

enable-signup: ${ENABLE_SIGNUP}
enable-login: ${ENABLE_LOGIN}
enable-reservations: ${ENABLE_RESERVATIONS}

keepalive-interval: "${KEEPALIVE}"
manager-interval: "${MANAGER}"

visitor-request-limit-burst: ${VISITOR_REQUEST_LIMIT_BURST}
visitor-request-limit-replenish: "${VISITOR_REQUEST_LIMIT_REPLENISH}"
visitor-message-daily-limit: ${VISITOR_MESSAGE_DAILY_LIMIT}

message-size-limit: "${MESSAGE_SIZE_LIMIT}"

# CORS: allow cross-origin API access (e.g. for ntfy_manager or other clients)
access-control-allow-origin: "*"
EOF

# base-url + attachments (both required together)
if bashio::config.has_value 'base_url' && [ -n "${BASE_URL}" ]; then
    bashio::log.info "base-url: ${BASE_URL}"
    cat >> "${CONFIG_FILE}" <<EOF

base-url: "${BASE_URL}"
attachment-cache-dir: /data/ntfy/attachments
attachment-total-size-limit: "${ATTACHMENT_TOTAL}"
attachment-file-size-limit: "${ATTACHMENT_FILE}"
attachment-expiry-duration: "${ATTACHMENT_EXPIRY}"
visitor-attachment-total-size-limit: "${VISITOR_ATTACHMENT_TOTAL}"
visitor-attachment-daily-bandwidth-limit: "${VISITOR_ATTACHMENT_BANDWIDTH}"
EOF
    bashio::log.info "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
    bashio::log.info " UnifiedPush / Matrix Push Gateway active:"
    bashio::log.info "   ${BASE_URL}/_matrix/push/v1/notify"
    bashio::log.info " Element Android → Settings → Notifications"
    bashio::log.info "   → UnifiedPush → select ntfy as the distributor"
    bashio::log.info "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
else
    bashio::log.info "No base-url set — local mode, attachments disabled"
    bashio::log.warning "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
    bashio::log.warning " UnifiedPush / Matrix Push Gateway NOT available!"
    bashio::log.warning " Reason: base_url is not set."
    bashio::log.warning " → set base_url in the add-on configuration,"
    bashio::log.warning "   e.g. https://ntfy.your-domain.tld"
    bashio::log.warning "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
fi

# upstream-url (iOS push)
if bashio::config.has_value 'upstream_base_url' && [ -n "${UPSTREAM_URL}" ]; then
    bashio::log.info "upstream-base-url: ${UPSTREAM_URL}"
    echo "upstream-base-url: \"${UPSTREAM_URL}\"" >> "${CONFIG_FILE}"
fi

if bashio::debug; then
    bashio::log.debug "=== server.yml ==="
    cat "${CONFIG_FILE}"
    bashio::log.debug "=================="
fi

# ---------------------------------------------------------------------------
# Create admin users via ntfy CLI (NTFY_AUTH_FILE env var, no --config flag)
# Fix 4: NTFY_PASSWORD env var used throughout — zero interactive prompts
# ---------------------------------------------------------------------------
# Run an ntfy CLI command; on failure log a warning with ntfy's own message
# (never silently ignore it). Returns the exit code of the command.
run_ntfy_cli() {
    local what="$1"
    shift
    local out="" rc=0
    out="$(NTFY_AUTH_FILE="${AUTH_FILE}" "$@" </dev/null 2>&1)" || rc=$?
    if [ "${rc}" -ne 0 ]; then
        bashio::log.warning "ntfy: ${what} failed (exit ${rc}): ${out}"
    fi
    return "${rc}"
}

# True if the ntfy user exists. The list is read into a variable first and the
# names are compared exactly: `ntfy user list | grep -q` ends the pipe early,
# ntfy then gets SIGPIPE and with pipefail the answer was wrong about half of
# the time, and "^user admin" also matched "admin2".
ntfy_user_exists() {
    local username="$1"
    local listing="" rc=0 line name
    listing="$(NTFY_AUTH_FILE="${AUTH_FILE}" ntfy user list </dev/null 2>&1)" || rc=$?
    if [ "${rc}" -ne 0 ]; then
        bashio::log.warning "ntfy: listing users failed (exit ${rc}): ${listing}"
        return 1
    fi
    while IFS= read -r line; do
        case "${line}" in
            "user "*)
                name="${line#user }"
                name="${name%% (*}"
                if [ "${name}" = "${username}" ]; then
                    return 0
                fi
                ;;
        esac
    done <<< "${listing}"
    return 1
}

create_admin() {
    local username="$1"
    local password="$2"
    if [ -z "${username}" ] || [ -z "${password}" ]; then
        return
    fi
    if ntfy_user_exists "${username}"; then
        bashio::log.info "Admin user '${username}' already exists — syncing password + role"
        NTFY_PASSWORD="${password}" run_ntfy_cli "changing the password of '${username}'" \
            ntfy user change-pass "${username}" || true
    else
        bashio::log.info "Creating admin user '${username}' …"
        NTFY_PASSWORD="${password}" run_ntfy_cli "creating the admin user '${username}'" \
            ntfy user add --role=admin "${username}" || true
    fi
    run_ntfy_cli "setting the role of '${username}' to admin" \
        ntfy user change-role "${username}" admin || true
    bashio::log.info "Admin user '${username}' ready"
}

# ---------------------------------------------------------------------------
# Ensure admin user has a tier (required for /v1/account/reservation)
# Must run before provision_ha_token so the user is fully set up first.
# ---------------------------------------------------------------------------
provision_admin_tier() {
    local username="$1"
    [ -z "${username}" ] && return

    # Create tier if it doesn't exist yet
    if ! NTFY_AUTH_FILE="${AUTH_FILE}" ntfy tier list </dev/null 2>/dev/null | grep -q "^tier admin"; then
        bashio::log.info "Creating 'admin' tier …"
        # NOTE: message-limit=0 is NOT "unlimited" despite the docs/UI saying
        # so — observed on ntfy v2.25.0, a real publish gets rejected with
        # HTTP 429 "limit reached: daily message quota reached" even though
        # the account page shows "Unlimited". Using a high concrete number
        # instead actually behaves as unlimited in practice.
        NTFY_AUTH_FILE="${AUTH_FILE}" ntfy tier add \
            --message-limit=1000000 \
            --message-expiry-duration=8760h \
            --email-limit=0 \
            --reservation-limit=100 \
            --attachment-file-size-limit=100M \
            --attachment-total-size-limit=10G \
            admin </dev/null 2>/dev/null || true
    else
        # Migration for installs created before this fix: an existing
        # 'admin' tier may still carry the broken message-limit=0. Detect
        # and repair it in place so upgrades self-heal without manual CLI
        # intervention.
        if NTFY_AUTH_FILE="${AUTH_FILE}" ntfy tier list </dev/null 2>/dev/null \
            | awk '/^tier admin/{f=1} f && /^tier /&&!/^tier admin/{f=0} f' \
            | grep -q "Message limit: 0$"; then
            bashio::log.warning "Existing 'admin' tier has message-limit=0 (broken on this ntfy version) — fixing to 1000000"
            NTFY_AUTH_FILE="${AUTH_FILE}" ntfy tier change --message-limit=1000000 admin </dev/null 2>/dev/null || true
        fi
    fi

    # Assign tier to admin user
    bashio::log.info "Assigning 'admin' tier to '${username}' …"
    NTFY_AUTH_FILE="${AUTH_FILE}" \
        ntfy user change-tier "${username}" admin </dev/null 2>/dev/null || true
}

# ---------------------------------------------------------------------------
# Fix 1: Token auto-provisioning
# Creates one persistent HA integration token at first startup.
# Token is written to /data/ntfy/ha_token.txt (survives restarts + backups).
# On subsequent starts the file already exists — no duplicate token created.
# ---------------------------------------------------------------------------
# Writes a copy of the token to the add-on config folder so it can be read
# without the log (Samba/SSH). The log only ever shows the start of the token.
export_ha_token() {
    if [ -d /config ]; then
        (umask 077; printf '%s\n' "$1" > "${HA_TOKEN_COPY}")
    fi
}

provision_ha_token() {
    local username="$1"

    # Token already exists — nothing to do regardless of username
    if [ -f "${HA_TOKEN_FILE}" ]; then
        local existing
        existing=$(cat "${HA_TOKEN_FILE}")
        bashio::log.info "HA token already provisioned → ${existing:0:8}…"
        export_ha_token "${existing}"
        return
    fi

    # First run — need username to create token
    if [ -z "${username}" ]; then
        bashio::log.info "Token auto-provisioning skipped — set admin_username in Configuration to enable"
        return
    fi

    bashio::log.info "Provisioning HA integration token for '${username}' …"
    local token_output
    local token_rc=0
    # bashio runs with errexit: a failing command substitution would end the
    # whole add-on, so capture the exit code instead.
    token_output=$(NTFY_AUTH_FILE="${AUTH_FILE}" \
        timeout 15 ntfy token add --label="Home Assistant" "${username}" </dev/null 2>&1) || token_rc=$?

    if [ "${token_rc}" -eq 124 ]; then
        bashio::log.warning "Token provisioning timed out after 15s — skipping for now."
        bashio::log.warning "Run manually: ntfy_token ${username} 'Home Assistant'"
        return
    fi

    # ntfy token add output format: "token tk_XXXX (label) expires never"
    local token
    token=$(printf '%s' "${token_output}" | grep -oE 'tk_[A-Za-z0-9]+' | head -1 || true)

    if [ -n "${token}" ]; then
        printf '%s\n' "${token}" > "${HA_TOKEN_FILE}"
        chmod 600 "${HA_TOKEN_FILE}"
        export_ha_token "${token}"
        bashio::log.info "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
        bashio::log.info " HA integration token created: ${token:0:8}…"
        bashio::log.info " The full token is not printed to the log."
        bashio::log.info " Read it from the add-on config folder:"
        bashio::log.info "   /addon_configs/<slug>_ntfy/ha_token.txt"
        bashio::log.info " Then use it in secrets.yaml as ntfy_token."
        bashio::log.info "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
    else
        # The output may contain a token (if only the parsing failed): mask it.
        bashio::log.warning "Token provisioning failed — output: $(printf '%s' "${token_output}" | sed -E 's/tk_[A-Za-z0-9]+/tk_…/g')"
        bashio::log.warning "Run manually: ntfy_token ${username} 'Home Assistant'"
    fi
}

# ---------------------------------------------------------------------------
# The ntfy CLI (user/tier/token) refuses to work until the server has created
# the auth database ("auth-file does not exist; please start the server at least
# once"). On a fresh install start the server once, wait until it is healthy and
# stop it again; then the CLI calls below work. The CLI calls swallow errors
# (|| true), so without this the admin user and token silently never exist.
# ---------------------------------------------------------------------------
ensure_auth_db() {
    [ -f "${AUTH_FILE}" ] && return
    bashio::log.info "First start: initializing the auth database …"
    ntfy serve --config="${CONFIG_FILE}" >/dev/null 2>&1 &
    local pid=$!
    for _ in $(seq 1 30); do
        if [ -f "${AUTH_FILE}" ] && curl -sf "http://127.0.0.1:4280/v1/health" >/dev/null 2>&1; then
            break
        fi
        sleep 1
    done
    kill "${pid}" 2>/dev/null || true
    wait "${pid}" 2>/dev/null || true
    if [ ! -f "${AUTH_FILE}" ]; then
        bashio::log.warning "Auth database was not created — admin user and token cannot be provisioned on this start."
    fi
}

# ---------------------------------------------------------------------------
# Execution order: auth db → user → tier → token
# ---------------------------------------------------------------------------
ensure_auth_db
create_admin "${ADMIN_USER}" "${ADMIN_PASS}"
provision_admin_tier "${ADMIN_USER}"
provision_ha_token "${ADMIN_USER}"

if [ -n "${BASE_URL}" ]; then
    bashio::log.info "Starting ntfy on port 4280 (base-url: ${BASE_URL})"
else
    bashio::log.info "Starting ntfy on port 4280 (open it at http://<ha-host>:4280)"
fi
exec ntfy serve --config="${CONFIG_FILE}" 2>&1
